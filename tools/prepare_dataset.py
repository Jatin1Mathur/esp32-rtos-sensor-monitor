"""Converts the UCI/Kaggle "Occupancy Detection" data into the files this project uses.

Input : datatest.txt from the original dataset (Candanedo & Feldheim, 2016)
Output: data/office_room_2015.csv   - clean CSV used by host tests and the replay client
        src/replay_data.h           - the same readings as a C array for the firmware

Usage:  python tools/prepare_dataset.py path/to/datatest.txt
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV_OUT = ROOT / "data" / "office_room_2015.csv"
HEADER_OUT = ROOT / "src" / "replay_data.h"


def load(raw_path: Path) -> list[dict]:
    rows = []
    with raw_path.open(newline="") as f:
        reader = csv.reader(f)
        next(reader)  # header: "date","Temperature","Humidity","Light","CO2","HumidityRatio","Occupancy"
        for line in reader:
            # each data line starts with a row id that has no header column
            _, date, temp, rh, _light, _co2, _ratio, occ = line
            rows.append(
                {
                    "timestamp": date,
                    "temperature_c": round(float(temp), 2),
                    "humidity_pct": round(float(rh), 2),
                    "occupancy": int(occ),
                }
            )
    return rows


def validate(rows: list[dict]) -> None:
    assert rows, "no rows"
    for r in rows:
        assert -45 <= r["temperature_c"] <= 130, r  # SHT3x measuring range
        assert 0 <= r["humidity_pct"] <= 100, r
    stamps = [r["timestamp"] for r in rows]
    assert stamps == sorted(stamps), "timestamps must be in order"


def write_csv(rows: list[dict]) -> None:
    CSV_OUT.parent.mkdir(exist_ok=True)
    with CSV_OUT.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["timestamp", "temperature_c", "humidity_pct", "occupancy"])
        writer.writeheader()
        writer.writerows(rows)


def write_header(rows: list[dict]) -> None:
    lines = [
        "// GENERATED by tools/prepare_dataset.py - do not edit by hand.",
        "// Real office-room readings (UCI Occupancy Detection, CC BY 4.0, see data/README.md).",
        f"// {len(rows)} readings, 1 per minute, {rows[0]['timestamp']} .. {rows[-1]['timestamp']}",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        '#include "sm/types.h"',
        "",
        "namespace replay_data {",
        "",
        "// Stored in flash (const), not RAM.",
        "const sm::Reading kReadings[] = {",
    ]
    lines += [f"    {{{r['temperature_c']:.2f}f, {r['humidity_pct']:.2f}f}}," for r in rows]
    lines += [
        "};",
        "",
        "constexpr size_t kCount = sizeof(kReadings) / sizeof(kReadings[0]);",
        "",
        "}  // namespace replay_data",
        "",
    ]
    HEADER_OUT.write_text("\n".join(lines))


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    rows = load(Path(sys.argv[1]))
    validate(rows)
    write_csv(rows)
    write_header(rows)
    temps = [r["temperature_c"] for r in rows]
    hums = [r["humidity_pct"] for r in rows]
    print(f"{len(rows)} rows  {rows[0]['timestamp']} .. {rows[-1]['timestamp']}")
    print(f"temperature {min(temps)} .. {max(temps)} C, humidity {min(hums)} .. {max(hums)} %")


if __name__ == "__main__":
    main()
